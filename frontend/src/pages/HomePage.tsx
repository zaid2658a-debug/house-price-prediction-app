import { useState } from "react";
import { useNavigate } from "react-router-dom";
import PredictionForm from "../components/PredictionForm";
import { predictPrice, PredictionApiError } from "../api/predictionClient";
import type { PredictionRequest } from "../types/prediction";

export default function HomePage() {
  const navigate = useNavigate();
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleSubmit(payload: PredictionRequest) {
    setSubmitting(true);
    setError(null);
    try {
      const result = await predictPrice(payload);
      navigate("/result", {
        state: { predictedPrice: result.predicted_price, inputs: payload },
      });
    } catch (err) {
      const message =
        err instanceof PredictionApiError
          ? err.message
          : "Couldn't reach the prediction service. Please try again.";
      setError(message);
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <div className="sheet">
      <span className="crop crop-tl" aria-hidden="true" />
      <span className="crop crop-tr" aria-hidden="true" />
      <span className="crop crop-bl" aria-hidden="true" />
      <span className="crop crop-br" aria-hidden="true" />

      <header className="title-block">
        <span className="title-block__eyebrow">Sheet 001 / Property Valuation</span>
        <span>India · Residential</span>
      </header>

      <main>
        <div className="hero">
          <h1>What's this property worth?</h1>
          <p className="hero__sub">
            Enter the property specs below. The estimate is generated by a model
            trained on real listing data — carpet area, location, and
            classification all factor into the number.
          </p>
        </div>

        {error && (
          <div className="banner banner--danger" role="alert">
            {error}
          </div>
        )}

        <PredictionForm onSubmit={handleSubmit} submitting={submitting} />
      </main>
    </div>
  );
}